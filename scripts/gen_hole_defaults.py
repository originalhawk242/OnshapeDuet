"""Generate src/onshape_duet/features/hole_defaults.py from the captured hole featurespec.

Each default is exactly what a generic add sends for the same parameter: the spec is parsed by
generic.specs and every parameter rendered by generic.build.default_param, so the typed and
generic paths cannot drift apart.

Dev script: python scripts/gen_hole_defaults.py
"""
import gzip
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from onshape_duet.generic.build import default_param  # noqa: E402
from onshape_duet.generic.specs import parse_feature_specs  # noqa: E402

SPECS = ROOT / "tests" / "fixtures" / "feature_specs.json.gz"
OUT = ROOT / "src" / "onshape_duet" / "features" / "hole_defaults.py"

HEADER = ('# Generated by scripts/gen_hole_defaults.py from tests/fixtures/feature_specs.json.gz.\n'
          '# Do not edit; regenerate with: python scripts/gen_hole_defaults.py\n')


def convert(spec: dict) -> tuple[list[dict], int]:
    """The default of every spec parameter that has one, as default_param renders it, and the
    number skipped (no defaultValue). A defaultValue that default_param cannot build is an
    error, not a silent skip."""
    raw = {p["parameterId"]: p for p in spec["parameters"]}
    (parsed,) = parse_feature_specs({"featureSpecs": [spec]})
    out, skipped = [], 0
    for ps in parsed.params:
        if not raw[ps.id].get("defaultValue"):
            skipped += 1
            continue
        d = default_param(ps)
        if d is None:
            raise ValueError(f"{ps.id}: default_param cannot build its default "
                             f"({ps.kind}, default {ps.default!r})")
        out.append(d)
    return out, skipped


def render(defaults: list[dict]) -> str:
    body = "".join(f"    {d!r},\n" for d in defaults)
    return f"{HEADER}\nHOLE_DEFAULTS: tuple[dict, ...] = (\n{body})\n"


def load_hole_spec() -> dict:
    with gzip.open(SPECS, "rt") as fh:
        specs = json.loads(fh.read())
    return next(s for s in specs["kept"] if s.get("featureType") == "hole")


def main() -> int:
    try:
        defaults, skipped = convert(load_hole_spec())
    except (ValueError, RuntimeError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    OUT.write_text(render(defaults))
    print(f"emitted {len(defaults)} parameters, skipped {skipped} (no default)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
